const entries = Object.entries(dictionary).flatMap(([category, keywords]) => keywords.map(keyword => ({ category, keyword })));

/** 이름에서 규칙상 이기는 키워드와 그 카테고리. 소비권장일 DB를 찾을 때도 이 키워드를 쓴다. */
export function matchIngredient(name: string): { keyword: string; category: string } | undefined {
  const text = name.toLowerCase();
  let best: { end: number; length: number; keyword: string; category: string } | undefined;
  for (const { category, keyword } of entries) {
    for (let start = text.indexOf(keyword); start >= 0; start = text.indexOf(keyword, start + 1)) {
      const end = start + keyword.length;
      if (keyword.length === 1 && end < text.length && text[end] !== ' ') continue;
      if (!best || end > best.end || (end === best.end && keyword.length > best.length)) best = { end, length: keyword.length, keyword, category };
    }
  }
  return best && { keyword: best.keyword, category: best.category };
}

export function classifyIngredient(name: string): string {
  return matchIngredient(name)?.category ?? FALLBACK_CATEGORY;
}
